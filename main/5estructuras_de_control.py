def main_aprendizaje():
    
    """
    Sentencia IF - ELSE
    Se evalúa la condición especificada en la sentencia if y en caso de cumplirse se ejecutará el bloque
    de código indentado (tabulado). En caso de que el resultado de la condición sea False, el bloque
    especificado no se ejecutará:
    
    """
    numero = 5
    if numero > 1:
        # Se ejecuta cuando la condicion es True
        print("El numero es mayor que 1")

    # Las condiciones pueden ser mas complejas

    edad = 16
    altura = 175
    
    # Las condiciones pueden ser mas complejas
    if (edad > 14 and altura > 160):
        print("Puede montarse en la montaña rusa")

    


if __name__=="__main__":
    main_aprendizaje()
